package OOPSBasicstoAdv.Interface.UsingDefaultStaticPrivateMethods;

class SmartLight implements SmartDevice {
    public void turnOn() {
        System.out.println("Smart Light is ON");
        System.out.println();
    }
    public void turnOff() {
        System.out.println("Smart Light is OFF");
        System.out.println();
    }
}
