package OOPSBasicstoAdv.Interface.UsingDefaultStaticPrivateMethods;
class SmartTV implements SmartDevice {
    public void turnOn() {
        System.out.println("Smart TV is ON");
        System.out.println();
    }

    public void turnOff() {
        System.out.println("Smart TV is OFF");
        System.out.println();
    }
}

